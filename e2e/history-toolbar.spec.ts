import {test, expect} from '@playwright/test'
import {disableFeatureHints, dismissOnboardingIfVisible, waitForAppShell} from './helpers'

test('history toolbar shortcut is optional, persists and inherits the toolbar color', async ({page}) => {
  await disableFeatureHints(page)
  await page.goto('/settings?tab=appearance&section=appearance_navigation')
  await waitForAppShell(page)
  await dismissOnboardingIfVisible(page)
  const toggle=page.getByTestId('settings-history-button').locator('input[type=checkbox]')
  const shortcut=page.locator('.history-toolbar-trigger')
  await expect(toggle).not.toBeChecked()
  await expect(shortcut).toHaveCount(0)
  const saved=page.waitForResponse(response=>response.url().includes('/api/Setting/showHistoryInAppBar')&&response.request().method()==='PUT'&&response.ok())
  await toggle.press('Space')
  await saved
  await expect(shortcut).toBeVisible()
  await expect(shortcut).not.toHaveClass(/text-primary|v-btn--variant-tonal/)
  const iconColor=await shortcut.evaluate(el=>getComputedStyle(el).color)
  const helpColor=await page.locator('.v-app-bar .mdi-help-circle-outline').evaluate(el=>getComputedStyle(el.closest('button')!).color)
  expect(iconColor).toBe(helpColor)
  await page.reload()
  await expect(page.getByTestId('settings-history-button')).toBeVisible({timeout:30_000})
  await expect(toggle).toBeChecked()
  await expect(shortcut).toBeVisible()
  await shortcut.click()
  await expect(page.locator('.change-history-dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.change-history-dialog')).not.toBeVisible()
  await toggle.press('Space')
  await expect(shortcut).toHaveCount(0)
  await page.goto('/settings?tab=database&section=change_history')
  await expect(page.locator('#settings-change-history')).toBeVisible({timeout:30_000})
  await expect(page.locator('#settings-change-history').getByRole('button')).toBeVisible()
  await page.unrouteAll({behavior:'wait'})
})
