import {test, expect} from '@playwright/test'
import {disableFeatureHints, openSettingsTab, dismissOnboardingIfVisible, waitForAppShell} from './helpers'

// Requires actual servers from scripts/webdav-fixture/setup.mjs; no WebDAV routes are mocked.
test.skip(process.env.WEBDAV_ACCEPTANCE !== '1', 'Opt in to real-server WebDAV acceptance')
for (const [implementation, port, root] of [
  ['Nextcloud', 18443, '/remote.php/dav/files/reader/'],
  ['Apache mod_dav', 18444, '/dav/'],
] as const) {
  test(`${implementation}: HTTPS connection, folder browser, import, metadata editor and player seek`, async ({page}) => {
    const healthSetting = await page.request.put('/api/Setting/startupHealthNotifications', {data: {value: '0'}})
    expect(healthSetting.ok()).toBe(true)
    await disableFeatureHints(page)
    await openSettingsTab(page, 'settings-doc-tab-connections')
    await page.getByRole('radio', {name: 'Network', exact: true}).click()
    const source = page.locator('#settings-nas')
    await source.getByRole('button', {name: /^(Add connection|Добавить подключение)$/}).click()
    const connectionEditor = page.locator('.nas-source-editor')
    await connectionEditor.getByRole('combobox', {name: /^(Protocol|Протокол)$/}).press('Enter')
    await page.getByRole('option', {name: 'WebDAV HTTPS', exact: true}).click()
    await expect(connectionEditor.getByLabel(/^(Port|Порт)$/, {exact: true})).toHaveValue('443')
    await connectionEditor.getByLabel(/^(Name|Название)$/, {exact: true}).fill(`Acceptance ${implementation}`)
    await connectionEditor.getByLabel(/^(NAS host|Адрес NAS)$/, {exact: true}).fill('127.0.0.1')
    await connectionEditor.getByLabel(/^(Port|Порт)$/, {exact: true}).fill(String(port))
    await connectionEditor.getByLabel(/^(Username|Пользователь)$/, {exact: true}).fill('reader')
    await connectionEditor.getByLabel(/^(Root folder|Корневая папка)$/, {exact: true}).fill(root)
    await connectionEditor.getByLabel(/^(Password|Пароль)$/, {exact: true}).fill('webdav-acceptance-password')
    const saving = page.waitForResponse(response => response.url().endsWith('/api/nas/connections') && response.request().method() === 'POST')
    await connectionEditor.getByRole('button', {name: /^(Check and save|Проверить и сохранить)$/}).click()
    const saved = await saving
    expect(saved.status(), await saved.text()).toBe(200)
    const connection = await saved.json()
    await expect(connectionEditor).toBeHidden()
    const browser = source.locator('.media-folder-browser')
    await browser.locator('.media-folder-browser__list .v-list-item').filter({hasText: 'Кино & тест'}).click()
    const file = browser.locator('.media-folder-browser__list .v-list-item').filter({hasText: 'video 100% #.mp4'})
    await expect(file).toBeVisible()
    await file.getByRole('button', {name: /^(Preview without adding to library|Просмотреть без добавления в библиотеку)$/}).click()
    const player = page.locator('#player')
    const video = player.locator('video[data-player-bound]')
    await expect(player).toBeVisible()
    await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).duration)).toBe(8)
    await video.evaluate(element => { const video = element as HTMLVideoElement; video.pause(); video.currentTime = 5 })
    await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThanOrEqual(5)
    await expect(player.locator('.btn-edit-video, .mark-buttons')).toHaveCount(0)
    await player.locator('.player-close-btn').click()
    await expect(player).toBeHidden()
    await file.getByRole('checkbox').check()
    const importing = page.waitForResponse(response => response.url().endsWith('/api/nas/import-batch'))
    await page.getByRole('button', {name: /^(Add selected|Добавить выбранные)$/}).click()
    const imported = (await (await importing).json()).results[0]
    expect(imported).toMatchObject({ok: true, created: true})
    await expect(file.getByRole('checkbox')).toBeDisabled()
    await browser.screenshot({path: test.info().outputPath(`${implementation}-browser.png`)})
    const mediaResponse = await page.request.get(`/api/Media/${imported.id}`)
    const media = await mediaResponse.json()
    await page.goto(`/media?mediaTypeId=${media.mediaTypeId}`)
    await waitForAppShell(page); await dismissOnboardingIfVisible(page)
    const card = page.locator(`[data-item-id="${imported.id}"]`)
    await card.locator('.description').dblclick()
    const editor = page.locator('.edit-dialog-card')
    await editor.getByRole('button', {name: /^(File copies|Копии файла)$/}).click()
    await expect(editor.locator('.media-catalog-source-info')).toContainText(`Acceptance ${implementation}`)
    const bookmark = `${implementation}: metadata saved over WebDAV HTTPS`
    await editor.locator('textarea:not([readonly])').last().fill(bookmark)
    await editor.getByRole('button', {name: /^(Save|Сохранить)$/}).click()
    await expect(editor).toBeHidden()
    expect((await (await page.request.get(`/api/Media/${imported.id}`)).json()).bookmark).toBe(bookmark)
    await card.locator('.description').dblclick()
    await expect(editor.locator('textarea:not([readonly])').last()).toHaveValue(bookmark)
    await editor.screenshot({path: test.info().outputPath(`${implementation}-metadata.png`)})
    await editor.getByRole('button', {name: /^(Save|Сохранить)$/}).click()
    await expect(editor).toBeHidden()
    await card.locator('.video-preview-container').click()
    await expect(player).toBeVisible()
    await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).duration)).toBe(8)
    await video.evaluate(element => { const video = element as HTMLVideoElement; video.pause(); video.currentTime = 6 })
    await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThanOrEqual(6)
    await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2)
    expect(await video.evaluate(element => (element as HTMLVideoElement).error)).toBeNull()
    await player.screenshot({path: test.info().outputPath(`${implementation}-player.png`)})
    await player.locator('.player-close-btn').click()
    // Verify reconnect uses the original imported card and keeps its local metadata.
    expect((await page.request.post(`/api/nas/connections/${connection.id}/disconnect`)).ok()).toBe(true)
    expect((await (await page.request.get(`/api/Media/${imported.id}`)).json()).bookmark).toBe(bookmark)
    const restored = await page.request.put(`/api/nas/connections/${connection.id}`, {data: {name: connection.name,
      protocol: 'webdav', host: '127.0.0.1', port, root, username: 'reader', password: 'webdav-acceptance-password'}})
    expect(restored.ok()).toBe(true)
    const duplicate = await page.request.post('/api/nas/import', {data: {connectionId: connection.id, path: 'Кино & тест/video 100% #.mp4'}})
    expect(await duplicate.json()).toMatchObject({id: imported.id, created: false})
  })
}
